"""Loads the data files and turns CSV rows into API objects.

Files (all in data/):
  experiments.csv  - one row per test, filled by the data team
  materials.csv    - allowed material names + display names
  analysis.json    - AI summaries, generated by analyze.py ({experiment_id: {...}})
  library.json     - stowage item library (planner items, swaps, PSI material keys)
"""

import json
import math
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

import pandas as pd
from pydantic import ValidationError

from .schemas import Analysis, Experiment, Material, Preset, Range

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
EXPERIMENTS_CSV = DATA_DIR / "experiments.csv"
MATERIALS_CSV = DATA_DIR / "materials.csv"
PRESETS_JSON = DATA_DIR / "presets.json"
ANALYSIS_JSON = DATA_DIR / "analysis.json"
LIBRARY_JSON = DATA_DIR / "library.json"

NUMERIC_COLUMNS = [
    "oxygen_pct_min", "oxygen_pct_max",
    "pressure_psi_min", "pressure_psi_max",
    "airflow_cm_s_min", "airflow_cm_s_max",
]


# ------------------------------------------------------------------ helpers

def clean(value: Any) -> Any:
    """NaN / blank strings -> None, numpy numbers -> plain Python (JSON-safe)."""
    if value is None:
        return None
    if isinstance(value, float) and math.isnan(value):
        return None
    if isinstance(value, str) and not value.strip():
        return None
    if hasattr(value, "item"):  # numpy int/float
        value = value.item()
        if isinstance(value, float) and math.isnan(value):
            return None
    return value


# ------------------------------------------------------------------ loaders (cached)

@lru_cache(maxsize=1)
def load_experiments() -> pd.DataFrame:
    """Verified experiments as a DataFrame (used by matching.py and main.py)."""
    df = pd.read_csv(EXPERIMENTS_CSV, dtype={"id": str})
    verified = df["verified"].astype(str).str.strip().str.lower() == "yes"
    df = df[verified].copy()
    for col in NUMERIC_COLUMNS:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    return df.reset_index(drop=True)


@lru_cache(maxsize=1)
def load_materials() -> List[Material]:
    df = pd.read_csv(MATERIALS_CSV)
    materials = []
    for r in df.to_dict("records"):
        materials.append(Material(
            material=r["material"],
            display_name=r["display_name"],
            fuel_type=r["fuel_type"],
            description=clean(r.get("description")) or "",
            investigations=[s.strip() for s in str(r.get("investigations") or "").split(",") if s.strip()],
            priority=int(r["priority"]),
        ))
    return sorted(materials, key=lambda m: (m.priority, m.display_name))


@lru_cache(maxsize=1)
def load_presets() -> List[Preset]:
    return [Preset(**p) for p in json.loads(PRESETS_JSON.read_text())]


@lru_cache(maxsize=1)
def load_analysis() -> Dict[str, Analysis]:
    """AI summaries keyed by experiment id. Missing file -> {} (analyze.py not run yet)."""
    if not ANALYSIS_JSON.exists():
        return {}
    raw = json.loads(ANALYSIS_JSON.read_text())
    out = {}
    for exp_id, entry in raw.items():
        try:
            out[exp_id] = Analysis(**entry)
        except ValidationError:
            print(f"[data] skipping malformed analysis for {exp_id}")
    return out


@lru_cache(maxsize=1)
def load_library() -> List[Dict[str, Any]]:
    """Stowage item library, copied from the planner prototype (BASE_LIB).
    material_key links an item to materials.csv / experiments.csv; null = no NASA tests."""
    return json.loads(LIBRARY_JSON.read_text())


def get_library_item(key: Optional[str]) -> Optional[Dict[str, Any]]:
    if not key:
        return None
    return next((x for x in load_library() if x["key"] == key), None)


def reload() -> None:
    """Forget cached data so the next request re-reads the files."""
    load_library.cache_clear()
    load_experiments.cache_clear()
    load_materials.cache_clear()
    load_presets.cache_clear()
    load_analysis.cache_clear()


# ------------------------------------------------------------------ lookups

def get_material(key: str) -> Optional[Material]:
    """Case-insensitive lookup by material key, e.g. 'pmma' -> PMMA."""
    key = key.strip().lower()
    return next((m for m in load_materials() if m.material.lower() == key), None)


def get_preset(preset_id: str) -> Optional[Preset]:
    return next((p for p in load_presets() if p.id == preset_id), None)


def row_to_experiment(row: Any) -> Experiment:
    """One experiments.csv row (pandas Series or dict) -> Experiment for the API.
    source_quote and verified are internal and left out."""
    r = {k: clean(v) for k, v in dict(row).items()}
    return Experiment(
        id=str(r["id"]),
        name=r.get("name") or "",
        investigation=r.get("investigation") or "",
        fuel_type=r.get("fuel_type"),
        material=r.get("material"),
        oxygen_pct=Range(min=r.get("oxygen_pct_min"), max=r.get("oxygen_pct_max")),
        pressure_psi=Range(min=r.get("pressure_psi_min"), max=r.get("pressure_psi_max")),
        airflow_cm_s=Range(min=r.get("airflow_cm_s_min"), max=r.get("airflow_cm_s_max")),
        gravity=r.get("gravity"),
        outcome=r.get("outcome"),
        outcome_category=r.get("outcome_category"),
        description=r.get("description"),
        source_url=r.get("source_url"),
        analysis=load_analysis().get(str(r["id"])),
    )


def get_experiment(exp_id: str) -> Optional[Experiment]:
    df = load_experiments()
    rows = df[df["id"] == exp_id]
    return row_to_experiment(rows.iloc[0]) if not rows.empty else None


def list_experiments(
    investigation: Optional[str] = None,
    material: Optional[str] = None,
    fuel_type: Optional[str] = None,
    outcome_category: Optional[str] = None,
    environment: Optional[str] = None,
    sort: str = "relevance",
) -> List[Experiment]:
    """Filtered experiments for GET /experiments.
    investigation matches partially (e.g. 'FLEX' or 'PSI-69'); other filters are exact, case-insensitive.
    sort: 'relevance' (AI score, highest first; unscored last) or 'id'."""
    df = load_experiments()
    if investigation:
        q = investigation.strip()
        df = df[df["investigation"].str.contains(q, case=False, na=False, regex=False)
                | df["name"].str.contains(q, case=False, na=False, regex=False)   # FLEX, SAFFIRE, BASS-II, BRE
                | df["id"].str.upper().str.startswith(q.upper())]
    if material:
        df = df[df["material"].fillna("").str.lower() == material.strip().lower()]
    if fuel_type:
        df = df[df["fuel_type"].fillna("").str.lower() == fuel_type.strip().lower()]
    if outcome_category:
        df = df[df["outcome_category"].fillna("").str.lower() == outcome_category.strip().lower()]

    items = [row_to_experiment(r) for _, r in df.iterrows()]

    if environment:
        env = environment.strip().lower()
        items = [e for e in items if e.analysis and env in [x.lower() for x in e.analysis.environments]]

    if sort == "relevance":
        items.sort(key=lambda e: (
            -(e.analysis.fire_safety_relevance or 0) if e.analysis else 1,
            e.id,
        ))
    else:
        items.sort(key=lambda e: e.id)
    return items


def experiment_count() -> int:
    return len(load_experiments())
